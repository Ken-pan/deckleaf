import { readFileSync, writeFileSync, renameSync, mkdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { Resvg } from '@resvg/resvg-js';
import { fileURLToPath } from 'node:url';
import JSZip from 'jszip';

// Reviewed vector → shipped derivatives, cache identity and downloadable kit.
import './adopt-brand.mjs';
const root = new URL('../', import.meta.url);
const read = path => readFileSync(new URL(path, root));
const write = (path, value) => { const target = new URL(path, root), temp = new URL(`${path}.brand-${process.pid}.tmp`, root); writeFileSync(temp, value); renameSync(temp, target); };
const hash = value => createHash('sha256').update(value).digest('hex');
const source = read('public/brand/logo.svg').toString();
const paths = [...source.matchAll(/<path\b[^>]*\/>/g)].map(match => match[0]).join('\n    ');
const ink = source.match(/<svg[^>]*fill="(#[\da-f]{6})"/i)?.[1];
if (!paths || !ink || !source.includes('viewBox="0 0 100 100"')) throw new Error('Expected the reviewed 100-unit brand mark');
const revision = hash(source).slice(0, 12);
const url = path => `${path}?v=${revision}`;
const files = ['brand/logo.svg'];
const save = (path, svg) => { write(`public/${path}`, svg + '\n'); files.push(path); };

save('favicon.svg', `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32">
  <rect width="32" height="32" rx="8" fill="${ink}"/>
  <g transform="translate(1.5 1.5) scale(.29)" fill="#fff">${paths}</g>
</svg>`);
save('brand/app-icon.svg', `<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024">
  <defs><linearGradient id="porcelain" x2="0" y2="1"><stop stop-color="#fff"/><stop offset="1" stop-color="#f3f6f3"/></linearGradient></defs>
  <rect x="100" y="100" width="824" height="824" rx="185" fill="url(#porcelain)" stroke="#e1e8e3"/>
  <g transform="translate(136 152) scale(7.2)" fill="${ink}">${paths}</g>
</svg>`);
save('brand/apple-touch-icon.svg', `<svg xmlns="http://www.w3.org/2000/svg" width="180" height="180" viewBox="0 0 180 180">
  <rect width="180" height="180" fill="${ink}"/>
  <g transform="translate(23 25) scale(1.3)" fill="#fff">${paths}</g>
</svg>`);
for (const [input, output, size] of [
  ['brand/logo.svg', 'brand/logo.png', 1024],
  ['brand/app-icon.svg', 'brand/app-icon.png', 1024],
  ['brand/app-icon.svg', 'brand/app-icon-512.png', 512],
  ['brand/app-icon.svg', 'brand/app-icon-192.png', 192],
  ['brand/apple-touch-icon.svg', 'brand/apple-touch-icon.png', 180],
  ['favicon.svg', 'brand/favicon-32.png', 32],
  ['favicon.svg', 'brand/favicon-16.png', 16],
]) {
  const image = new Resvg(read(`public/${input}`), {fitTo: {mode: 'width', value: size}, font: {loadSystemFonts: false}}).render();
  write(`public/${output}`, image.asPng()); files.push(output);
}

// ICO contains PNG frames for browsers/platforms without SVG favicon support.
const frames = [16, 32].map(size => ({size, bytes: read(`public/brand/favicon-${size}.png`)}));
const header = Buffer.alloc(6 + 16 * frames.length); header.writeUInt16LE(1, 2); header.writeUInt16LE(frames.length, 4);
let offset = header.length;
frames.forEach(({size, bytes}, index) => {
  const at = 6 + index * 16; header[at] = header[at + 1] = size;
  header.writeUInt16LE(1, at + 4); header.writeUInt16LE(32, at + 6);
  header.writeUInt32LE(bytes.length, at + 8); header.writeUInt32LE(offset, at + 12); offset += bytes.length;
});
write('public/favicon.ico', Buffer.concat([header, ...frames.map(frame => frame.bytes)])); files.push('favicon.ico');

const urls = {logo: url('/brand/logo.svg'), favicon: url('/favicon.svg'), fallbackIcon: url('/favicon.ico'), touchIcon: url('/brand/apple-touch-icon.png')};
write('src/brand-assets.ts', `// Generated by npm run build:brand. Do not edit.\nexport const BRAND_ASSETS = ${JSON.stringify({revision, ...urls}, null, 2)} as const;\n`);
write('src/brand-assets.css', `/* Generated by npm run build:brand. Do not edit. */\n:root { --brand-logo: url('${urls.logo}'); }\n`);
for (const path of ['index.html', 'characters.html', 'brand.html']) {
  let html = read(path).toString();
  html = html.replace(/<link\b[^>]*\brel="(?:icon|alternate icon|apple-touch-icon)"[^>]*>\s*/g, '');
  const links = `<link rel="alternate icon" href="${urls.fallbackIcon}" />\n    <link rel="icon" type="image/svg+xml" href="${urls.favicon}" />\n    <link rel="apple-touch-icon" href="${urls.touchIcon}" />\n  `;
  write(path, html.replace('</head>', links + '</head>'));
}

const pluginPath = 'plugins/figma-export/ui.html';
let plugin = read(pluginPath).toString();
const pluginTitle = plugin.match(/<h2\b[^>]*>([\s\S]*?)<\/h2>/)?.[1] || 'Export to Decksprig';
const pluginMark = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100" width="28" height="28" fill="currentColor" aria-hidden="true">${paths}</svg>`;
const pluginHeader = `<!-- deck-studio-brand:start -->\n<div class="plugin-brand" data-brand-revision="${revision}" style="display:flex;align-items:center;gap:10px;margin-bottom:16px;color:var(--figma-color-text)">${pluginMark}<h2 style="margin:0">${pluginTitle}</h2></div>\n<!-- deck-studio-brand:end -->`;
plugin = /<!-- deck-studio-brand:start -->[\s\S]*?<!-- deck-studio-brand:end -->/.test(plugin)
  ? plugin.replace(/<!-- deck-studio-brand:start -->[\s\S]*?<!-- deck-studio-brand:end -->/, pluginHeader)
  : plugin.replace(/<h2\b[^>]*>[\s\S]*?<\/h2>/, pluginHeader);
write(pluginPath, plugin);

const trace = JSON.parse(read('public/brand/references/approved-logo-trace.json'));
const manifest = {name: 'Decksprig', revision, master: 'brand/logo.svg', masterSha256: hash(source), sourceSha256: trace.sha256, defaultInk: ink, pathCount: [...source.matchAll(/<path\b/g)].length, urls, files: files.map(path => ({path, sha256: hash(read(`public/${path}`)), bytes: read(`public/${path}`).length}))};
write('public/brand/manifest.json', JSON.stringify(manifest, null, 2) + '\n');

const zip = new JSZip();
for (const path of [...files, 'brand/manifest.json']) zip.file(path, read(`public/${path}`), {date: new Date('2026-10-12T00:00:00Z')});
zip.file('README.md', read('docs/branding.md'), {date: new Date('2026-10-12T00:00:00Z')});
const output = new URL('output/brand/Decksprig-Brand-Kit.zip', root);
mkdirSync(fileURLToPath(new URL('output/brand/', root)), {recursive: true});
writeFileSync(output, await zip.generateAsync({type: 'nodebuffer', compression: 'DEFLATE'}));
console.log(`Generated ${files.length} brand assets, revision ${revision}, entry metadata, plugin mark and brand kit.`);
